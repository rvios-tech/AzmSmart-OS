export function guideFor(path: string): Guide | null {
  const key = Object.keys(GUIDES)
    .filter((k) => path === k || path.startsWith(k + "/"))
    .sort((a, b) => b.length - a.length)[0];
  return key ? GUIDES[key] : null;
}
